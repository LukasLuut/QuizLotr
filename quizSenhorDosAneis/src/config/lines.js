// Sorteia uma fala do personagem fora de "avoid": a fala anterior (texto) ou todas as já ditas
// na partida (Set). Esgotadas (as do Anel são poucas), volta a sortear sem repetir a última.
export function pickLine(persona, { isCorrect, usedRing, corruption = 0 }, avoid = null, last = null) {
  const lines = LINES[persona] || LINES.gandalf;
  let pool = isCorrect ? lines.correct : lines.wrong;
  if (corruption >= CORRUPTED_AT) pool = CORRUPTED_LINES;
  else if (usedRing && isCorrect && lines.ring) pool = lines.ring;
  const used = avoid instanceof Set ? avoid : new Set(avoid ? [avoid] : []);
  let options = pool.filter((l) => !used.has(l));
  if (options.length === 0) options = pool.length > 1 ? pool.filter((l) => l !== last) : pool;
  return options[Math.floor(Math.random() * options.length)];
}

