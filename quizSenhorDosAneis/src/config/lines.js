// Quando a corrupção passa deste valor, as falas viram as do Anel
export const CORRUPTED_AT = 70;
export const CORRUPTED_LINES = [
  "Meu precioso...",
  "Ele me chama...",
  "Só mais uma vez. Só mais uma...",
  "A escuridão está tão perto.",
  "Não consigo mais tirar os olhos dele.",
];

// Sorteia uma fala do personagem, sem repetir a anterior
export function pickLine(persona, { isCorrect, usedRing, corruption = 0 }, previous = null) {
  const lines = LINES[persona] || LINES.gandalf;
  let pool = isCorrect ? lines.correct : lines.wrong;
  if (corruption >= CORRUPTED_AT) pool = CORRUPTED_LINES;
  else if (usedRing && isCorrect && lines.ring) pool = lines.ring;
  const options = pool.length > 1 ? pool.filter((l) => l !== previous) : pool;
  return options[Math.floor(Math.random() * options.length)];
}
